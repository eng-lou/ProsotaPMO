# No arbitrary endpoint/SQL execution. Existing services retain their validations,
# CPM recomputation and cost synchronisation behaviour.
REGISTRY = {
    "resource": (Resource, ResourceCreate, ResourceUpdate, resource.create_resource, resource.update_resource),
    "calendar": (Calendar, CalendarCreate, CalendarUpdate, calendar.create_calendar, calendar.update_calendar),
    "calendar_break": (CalendarBreak, CalendarBreakCreate, CalendarBreakUpdate, calendar.create_break, calendar.update_break),
    "calendar_exception": (CalendarException, CalendarExceptionCreate, CalendarExceptionUpdate, calendar.create_exception, calendar.update_exception),
    "cost_element": (CostElement, CostElementCreate, CostElementUpdate, cost_element.create_cost_element, cost_element.update_cost_element),
    "activity": (Activity, None, ActivityUpdate, None, activity.update_activity),
    "schedule_settings": (SchedulePeriod, None, SchedulePeriodUpdate, None, schedule_period.update_period),
}
HIDDEN = {"project_id", "period_id", "schedule_period_id", "freeze_status", "baseline_locked_flag", "finish", "amend_relationships", "animation_profile_id", "qs_signoff_name", "qs_signoff_date"}


def fields_for(entity, action):
    schema = REGISTRY[entity][1 if action == "create" else 2]
    if schema is None:
        raise HTTPException(422, "Use the activity proposal tool to create a schedule.")
    return schema, set(schema.model_fields) - HIDDEN


def operation_schema(entity, action):
    model, allowed = fields_for(entity, action)
    raw = model.model_json_schema()
    properties = {k: v for k, v in raw["properties"].items() if k in allowed}
    data = {"type": "object", "properties": properties, "additionalProperties": False,
            "required": [k for k in raw.get("required", []) if k in allowed]}
    result = {"type": "object", "properties": {
        "entity": {"type": "string", "enum": [entity]},
        "action": {"type": "string", "enum": [action]},
        "label": {"type": "string", "description": "Human-readable record name and reason; identify assumptions and rate units."},
        "record_id": {"type": "string", "format": "uuid"},
        "data": data}, "required": ["entity", "action", "label", "data"], "additionalProperties": False}
    if action == "update": result["required"].append("record_id")
    return result


